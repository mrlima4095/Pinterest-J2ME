#!/usr/bin/env python3
"""Generate src/pinterest/util/Lang.java from the reduced langs/*.json tables.

Run from the repository root:  python3 tools/build_lang.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS_DIR = os.path.join(ROOT, "langs")
OUT = os.path.join(ROOT, "src", "pinterest", "util", "Lang.java")
CODES = ["en", "pt", "pl", "tr", "vi", "he"]


def java_string(value):
    return '"' + (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    ) + '"'


def main():
    tables = {}
    for code in CODES:
        with open(os.path.join(LANGS_DIR, code + ".json"), encoding="utf-8") as fh:
            tables[code] = json.load(fh)
    keys = sorted(set().union(*[set(t.keys()) for t in tables.values()]))

    lines = []
    add = lines.append
    add("package pinterest.util;")
    add("")
    add("// GENERATED BY tools/build_lang.py. DO NOT EDIT.")
    add("")
    add("import java.util.Hashtable;")
    add("")
    add("public class Lang {")
    add('  private static String c = "en";')
    add("  private static Hashtable d;")
    add("  private static boolean i = false;")
    add("")
    add("  private static final String[] KEYS = {")
    for start in range(0, len(keys), 10):
        chunk = ", ".join(java_string(k) for k in keys[start:start + 10])
        comma = "," if start + 10 < len(keys) else ""
        add("    " + chunk + comma)
    add("  };")
    for code in CODES:
        table = tables[code]
        add("")
        add("  private static class " + code.upper() + " {")
        add("    static final String[] VALUES = {")
        for start in range(0, len(keys), 4):
            chunk = ", ".join(
                java_string(table.get(k, tables["en"].get(k, k)))
                for k in keys[start:start + 4]
            )
            comma = "," if start + 4 < len(keys) else ""
            add("      " + chunk + comma)
        add("    };")
        add("  }")
    add("")
    add("  private static void l(String code) {")
    add("    if (d == null) {")
    add("      d = new Hashtable();")
    add("    } else {")
    add("      d.clear();")
    add("    }")
    add("    String[] vals;")
    first = True
    for code in CODES:
        if code == "en":
            continue
        prefix = "    if" if first else "    else if"
        first = False
        add(prefix + ' ("' + code + '".equals(code)) {')
        add("      vals = " + code.upper() + ".VALUES;")
        add("    }")
    add("    else {")
    add("      vals = EN.VALUES;")
    add("    }")
    add("    for (int j = 0; j < KEYS.length; j++) {")
    add("      d.put(KEYS[j], vals[j]);")
    add("    }")
    add("  }")
    add("")
    add("  public static void setLang(String code) {")
    add('    if (code != null && !code.equals(c)) {')
    add("      c = code;")
    add("      l(code);")
    add("      i = true;")
    add("    }")
    add("  }")
    add("")
    add("  public static String getCurrentLang() {")
    add("    return c;")
    add("  }")
    add('  public static String[] getAvailableLanguages() {')
    add("    return new String[] {" + ", ".join(java_string(c) for c in CODES) + "};")
    add("  }")
    add("")
    add("  public static String tr(String k) {")
    add("    if (!i) {")
    add("      l(c);")
    add("      i = true;")
    add("    }")
    add("    String v = (String) d.get(k);")
    add("    return v != null ? v : k;")
    add("  }")
    add("")
    add("  public static String tr(String k, String a) {")
    add('    return Utils.replace(tr(k), "{0}", a);')
    add("  }")
    add("")
    add("  private Lang() {}")
    add("}")
    add("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d keys, %d bytes)" % (OUT, len(keys), os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
